// npm run docs   Writes video-types.md from templates/types/*.json (and scenes.md through gen-scenes-doc).
import fs from 'node:fs';
import path from 'node:path';
import {listTypes, readType, root} from './lib/scaffold.mjs';

const body = listTypes().map(readType).map((t) => `## ${t.label} (\`${t.id}\`)
${t.summary}

- Length: ${t.lengthSec.min} to ${t.lengthSec.max} s, default ${t.lengthSec.default} s
- Ratios: ${t.ratios.join(', ')}
- Pace limit: ${t.pacing.maxSylPerSec} syllables per second
- Beat length: ${t.pacing.beatSec.min} to ${t.pacing.beatSec.max} s
- Longest static shot: ${t.pacing.maxStaticSec} s
- Default transition: ${t.pacing.defaultTransition}${t.pacing.defaultTransition === 'cut' ? '' : `, ${t.pacing.transitionSec} s`}

| Beat | Goal | Share | Scene | Alternatives |
|---|---|---|---|---|
${t.beats.map((b) => `| ${b.id} | ${b.goal} | ${Math.round(b.share * 100)}% | \`${b.scene}\` | ${b.altScenes.map((s) => `\`${s}\``).join(', ')} |`).join('\n')}

Retention rules:
${t.retention.map((r) => `- ${r}`).join('\n')}

Needs from you:
${t.needs.map((r) => `- ${r}`).join('\n')}
`).join('\n');

const doc = `# Video types

Generated by \`npm run docs\` from \`templates/types/\`. Do not edit by hand.

Pick a type when you create a job. It sets the beat skeleton in \`plan.json\`, and \`/storyboard\` and \`npm run check\` use its pacing and retention rules.

\`\`\`
npm run new -- my-video --type=saas-promo --ratio=16x9 --seconds=30
\`\`\`

\`--ratio\` and \`--seconds\` are optional, and default to the type's first ratio and default length. Lengths outside the type's range are allowed, and \`npm run check\` warns about them. To change a type, edit its JSON file and run \`npm run docs\`.

These values are starting rules of thumb for this studio, not measured benchmarks.

${body}`;
fs.writeFileSync(path.join(root, 'video-types.md'), doc);
console.log(`video-types.md: ${listTypes().length} types documented`);
