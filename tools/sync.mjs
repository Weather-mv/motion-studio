// Regenerates src/jobs.generated.ts from every jobs/*/plan.json + brand.json.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const jobsDir = path.join(root, 'jobs');
const ids = fs.existsSync(jobsDir)
  ? fs.readdirSync(jobsDir).filter((d) => fs.existsSync(path.join(jobsDir, d, 'plan.json')) && fs.existsSync(path.join(jobsDir, d, 'brand.json')))
  : [];
const imports = ids.map((id, i) => `import plan${i} from '../jobs/${id}/plan.json';\nimport brand${i} from '../jobs/${id}/brand.json';`).join('\n');
const list = ids.map((id, i) => `  {id: '${id}', plan: plan${i} as unknown as Plan, brand: brand${i} as unknown as Brand}`).join(',\n');
const out = `// AUTO-GENERATED by tools/sync.mjs. Do not edit.
import type {Brand, JobData, Plan} from './core/types';
${imports}

export const jobs: JobData[] = [
${list}
];
`;
fs.writeFileSync(path.join(root, 'src', 'jobs.generated.ts'), out);
console.log(`synced ${ids.length} job(s): ${ids.join(', ') || '(none)'}`);
