// npm run docs:scenes   Writes scenes.md from src/scenes/schemas.ts, so the docs cannot drift from the code.
import fs from 'node:fs';
import path from 'node:path';
import {z} from 'zod';
import {root} from './lib/scaffold.mjs';
import {loadSchemas} from './lib/load-schemas.mjs';

const {sceneSchemas, SCENE_NAMES, CLIENT_SCENES, NEW_SCENE_SUMMARIES} = await loadSchemas();

const describeType = (s) => {
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(' / ');
  if (s.anyOf) return s.anyOf.map(describeType).join(' or ');
  if (s.type === 'array') return s.items?.properties ? 'list of objects' : `list of ${describeType(s.items ?? {})}`;
  if (s.type === 'object') return 'object';
  return s.type ?? 'any';
};
const rows = (schema, prefix = '') => {
  const out = [];
  const required = new Set(schema.required ?? []);
  for (const [k, v] of Object.entries(schema.properties ?? {})) {
    if (k === 'blurIn' || k === 'blurOut') continue;
    const def = v.default !== undefined ? `\`${JSON.stringify(v.default)}\`` : required.has(k) ? 'required' : 'optional';
    out.push(`| \`${prefix}${k}\` | ${describeType(v)} | ${def} | ${v.description ?? ''} |`);
    const nested = v.type === 'array' ? v.items : v.type === 'object' ? v : null;
    if (nested?.properties) out.push(...rows(nested, `${prefix}${k}${v.type === 'array' ? '[]' : ''}.`));
  }
  return out;
};

const generic = SCENE_NAMES.filter((n) => !CLIENT_SCENES.includes(n));
const body = generic.map((n) => {
  const json = z.toJSONSchema(sceneSchemas[n], {io: 'input', unrepresentable: 'any'});
  return `## ${n}\n${NEW_SCENE_SUMMARIES[n] ?? ''}\n\n| Prop | Type | Default | What it does |\n|---|---|---|---|\n${rows(json).join('\n')}\n`;
}).join('\n');

const doc = `# Scenes

Generated by \`npm run docs:scenes\` from \`src/scenes/schemas.ts\`. Do not edit by hand.

Use a scene by naming it in a beat in \`plan.json\`. Colours, fonts and motion come from the job's \`brand.json\`, so scenes take no colour props. Times inside props are seconds from the start of the beat.

Every scene also accepts \`blurIn\` and \`blurOut\` (frames). See any job in Studio's sidebar to edit props live.

${body}
## captions overlay
Not a scene. Add \`"captions": {"maxWords": 3, "position": "bottom"}\` to \`meta\` in \`plan.json\`, then run \`npm run sync\`. Words and timing come only from \`edit/words.json\`. It shows 1 to 3 words at a time, breaks early at punctuation or a pause, and highlights the word being spoken.

| Field | Type | Default | What it does |
|---|---|---|---|
| \`maxWords\` | 1 to 3 | \`3\` | Words on screen at once |
| \`position\` | \`top\` / \`center\` / \`bottom\` | \`bottom\` | Where captions sit, always inside the safe zone |

## Client scenes
${CLIENT_SCENES.map((n) => `\`${n}\``).join(', ')} were written for one client job. They are kept working but are not generic, so the gallery leaves them out.

## Add a scene
1. Add its schema to \`src/scenes/schemas.ts\`, with a \`.describe()\` on every prop.
2. Create the component, using brand tokens from \`useTheme\`, motion from \`useMotion\` and layout from \`useStage\`.
3. Register it in \`src/scenes/registry.ts\`. The typecheck fails until schema and registry match.
4. Add a beat to \`jobs/gallery/plan.json\`, then run \`npm run docs:scenes\` and \`npm run check -- gallery\`.
`;
fs.writeFileSync(path.join(root, 'scenes.md'), doc);
console.log(`scenes.md: ${generic.length} scenes documented`);
